"""Port of the ``minecraft_java_remove`` role: its defaults, order and ignored failures.

Never dispatched without ``confirm_removal``. ``/opt/backups/minecraft-java``
and every Echoport archive stay, as with the role. Beyond the role, the
user's crontab file goes after ``userdel`` (the cron module leaves it, empty,
and userdel does not remove it).
"""

from __future__ import annotations

import ipaddress
import shlex
from collections.abc import Callable, Generator
from pathlib import PurePosixPath
from typing import Annotated, Self

from pydantic import Field, StrictBool, field_validator, model_validator
from pyinfra import host
from pyinfra.api import DeployError, FunctionCommand, OperationError, StringCommand, deploy, operation
from pyinfra.facts.server import Command
from pyinfra.operations import server, systemd
from pyinfra.operations.util import any_changed

from ops_deploy.base._common import AbsolutePath, RoleConfig, output, require_linux
from ops_deploy.core.config import ServiceName, UnixUser
from ops_deploy.services._lifecycle import kill_user_processes
from ops_deploy.services._lifecycle.ansible_remove import absent, service_absent, user_absent

Port = Annotated[int, Field(ge=1, le=65535)]
# The role's ``cron`` task: ``name: "Minecraft world backup"`` in the user's crontab.
CRON_NAME = "Minecraft world backup"
# Debian's cron spool, where ``crontab -u <user>`` keeps the user's file.
CRONTABS = "/var/spool/cron/crontabs"
# ansible.builtin.cron for a named job in a user crontab: drop every
# ``#Ansible: <name>`` line with the line after it; skip the three header
# lines some crontab implementations print; write only on a change.
CRON = r"""import re, subprocess, sys
action, user, name = sys.argv[1:4]
try:
    read = subprocess.run(['crontab', '-l', '-u', user], capture_output=True, text=True, timeout=60)
    if read.returncode not in (0, 1):
        raise RuntimeError
    lines = [line for count, line in enumerate(read.stdout.splitlines())
             if count > 2 or not (re.match(r'# DO NOT EDIT THIS FILE - edit the master and reinstall.', line)
                                  or re.match(r'# \(/tmp/.*installed on.*\)', line)
                                  or re.match(r'# \(.*version.*\)', line))]
    kept, job = [], False
    for line in lines:
        if job:
            job = False
        elif line == '#Ansible: ' + name:
            job = True
        else:
            kept.append(line)
    if action == 'inspect':
        print('present' if kept != lines else 'absent')
    elif kept != lines:
        body = '\n'.join(kept)
        subprocess.run(['crontab', '-u', user, '-'], input=body.rstrip('\r\n') + '\n' if body else '',
                       text=True, check=True, timeout=60)
except Exception:
    print('error')
    sys.exit(1)
"""


class MinecraftJavaRemoveConfig(RoleConfig):
    """The role's defaults (``/home/minecraft``, unlike the deploy's ``/opt/minecraft``)."""

    confirm_removal: StrictBool = False
    user: UnixUser = "minecraft"
    group: UnixUser = "minecraft"
    home: AbsolutePath = "/home/minecraft"
    service_name: ServiceName = "minecraft-java"
    port: Port = 25565
    rcon_port: Port = 25575
    firewall_allowed_networks: tuple[str, ...] = ("192.168.0.0/16", "10.0.0.0/8", "100.64.0.0/10")

    @field_validator("firewall_allowed_networks")
    @classmethod
    def networks(cls, value: tuple[str, ...]) -> tuple[str, ...]:
        try:
            # The role passes each entry to ufw as written.
            for item in value:
                ipaddress.ip_network(item, strict=False)
        except ValueError:
            raise ValueError("invalid game client network") from None
        return value

    @model_validator(mode="after")
    def bounded(self) -> Self:
        path = PurePosixPath(self.home)
        if len(path.parts) < 3 or ".." in path.parts:
            raise ValueError("home must be a service directory, not root, a top-level directory or a traversal")
        if self.user == "root" or self.group == "root":
            raise ValueError("root cannot be the Minecraft service account")
        return self


def _cron(action: str, cfg: MinecraftJavaRemoveConfig) -> str:
    return shlex.join(["/usr/bin/python3", "-I", "-B", "-c", CRON, action, cfg.user, CRON_NAME])


def _cron_unreadable() -> Callable[[], None]:
    def fail() -> None:
        raise OperationError("Cannot read the Minecraft user's crontab")

    return fail


@operation()
def _cron_job_absent(cfg: MinecraftJavaRemoveConfig) -> Generator[StringCommand | FunctionCommand, None, None]:
    state = host.get_fact(Command, command=_cron("inspect", cfg) + " || true")
    if state == "present":
        yield StringCommand(_cron("remove", cfg))
    elif state != "absent":
        yield FunctionCommand(_cron_unreadable(), (), {})


@deploy("Remove Minecraft Java")
def remove_minecraft_java(cfg: MinecraftJavaRemoveConfig) -> None:
    if not cfg.confirm_removal:
        raise DeployError("Minecraft Java removal requires confirm_removal=true")
    require_linux("Minecraft Java removal")
    # Two tasks, both with ignore_errors: stop, then disable.
    service_absent(
        name="Stop Minecraft for removal",
        service=cfg.service_name,
        label="Minecraft Java removal",
        disable=False,
        _ignore_errors=True,
    )
    service_absent(
        name="Disable Minecraft for removal",
        service=cfg.service_name,
        label="Minecraft Java removal",
        stop=False,
        _ignore_errors=True,
    )
    unit = f"/etc/systemd/system/{cfg.service_name}.service"
    unit_removal = absent(f"Remove {unit}", unit)
    systemd.daemon_reload(name="Reload systemd after the Minecraft unit removal")
    _cron_job_absent(name=f"Remove the {CRON_NAME!r} cron job", cfg=cfg, _ignore_errors=True)
    kill_user_processes(cfg.user, graceful=False)
    absent(f"Remove {cfg.home}", cfg.home)
    user_absent(name=f"Remove user {cfg.user}", user=cfg.user, remove_home=True)
    absent(f"Remove the {cfg.user} crontab", f"{CRONTABS}/{cfg.user}")
    server.group(name=f"Remove group {cfg.group}", group=cfg.group, present=False, _ignore_errors=True)
    # community.general.ufw (``delete: true``) with the role's arguments;
    # ignore_errors, also for a host without ufw. A rule that is not there
    # changes nothing ("Could not delete non-existent rule").
    if output("command -v ufw"):
        for network in cfg.firewall_allowed_networks:
            server.shell(
                name=f"Remove the Minecraft game port rule for {network}",
                commands=[f"ufw delete allow from {shlex.quote(network)} to any port {cfg.port} proto tcp"],
                _ignore_errors=True,
            )
        server.shell(
            name="Remove the Minecraft RCON port rule",
            commands=[f"ufw delete deny from any to any port {cfg.rcon_port} proto tcp"],
            _ignore_errors=True,
        )
    # The role's ``reload systemd`` handler, notified by the unit removal.
    systemd.daemon_reload(name="Reload systemd (the role's handler)", _if=any_changed(unit_removal))
