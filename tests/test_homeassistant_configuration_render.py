"""Byte-bound original template oracles; synthetic values, no inventory bodies."""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path

import jinja2
import pytest
import yaml
from pydantic import SecretStr, ValidationError

from ops_deploy.services.homeassistant.configuration_render import (
    ConfigurationSecrets,
    ConfigurationValues,
    render_configuration,
    render_include,
    render_secrets,
)
from ops_deploy.services.homeassistant.runtime_config import HomeAssistantRuntimeConfig

FIXTURE = Path(__file__).parent / "parity/homeassistant/configuration"
ORIGINAL = jinja2.Environment(
    loader=jinja2.FileSystemLoader(FIXTURE),
    undefined=jinja2.StrictUndefined,
    trim_blocks=True,
    keep_trailing_newline=True,
)


def test_original_bindings_and_declared_defaults() -> None:
    manifest = json.loads((FIXTURE / "source.json").read_text())
    for relative, row in manifest["files"].items():
        assert hashlib.sha256((FIXTURE / row["fixture"]).read_bytes()).hexdigest() == row["sha256"]
        if os.environ.get("OPS_LIBRARY_PATH"):
            source = Path(os.environ["OPS_LIBRARY_PATH"]) / "roles/homeassistant_deploy" / relative
            # The historical HEAD is provenance; byte-identical docs-only peers
            # remain valid. Actual source bytes are the compatibility contract.
            try:
                actual = source.read_bytes()
            except OSError as error:
                pytest.fail(f"Original configuration source unavailable: {relative} ({type(error).__name__})")
            assert hashlib.sha256(actual).hexdigest() == row["sha256"], relative
    defaults = yaml.safe_load((FIXTURE / "defaults__main.yml").read_text())
    for name, value in ConfigurationValues().model_dump(exclude={"db_url"}).items():
        original = defaults["homeassistant_" + name]
        assert (list(value) if isinstance(value, tuple) else value) == original


@pytest.mark.parametrize("override", [False, True])
def test_configuration_full_original_bytes_and_secret_boundary(override: bool) -> None:
    runtime = HomeAssistantRuntimeConfig(config_path="/srv/owned-config", data_path="/srv/owned-data")
    values = ConfigurationValues(
        **(
            {
                "external_url": "https://ha.example.test",
                "internal_url": "http://owned:8123",
                "latitude": 51.2,
                "longitude": -1.4,
                "elevation": 23,
                "trusted_proxies": ("192.0.2.3",),
                "logger_logs": {"owned.second": "error", "owned.first": "debug"},
                "db_url": SecretStr("postgresql://owned:synthetic@localhost/fixture"),
            }
            if override
            else {}
        )
    )
    context = {"homeassistant_" + k: v for k, v in values.model_dump(exclude={"db_url"}).items()}
    context.update(
        homeassistant_data_path=runtime.data_path,
        homeassistant_db_url=(
            values.db_url.get_secret_value()
            if values.db_url is not None
            else "sqlite:////srv/owned-config/home-assistant_v2.db"
        ),
    )
    rendered = render_configuration(runtime, values)
    assert rendered.get_secret_value() == ORIGINAL.get_template("configuration.yaml.j2").render(**context)
    assert "synthetic" not in repr(values)
    assert "recorder:" not in repr(rendered)
    assert "recorder:" not in str(rendered)
    assert "Generated by Ansible deployment" in rendered.get_secret_value()


@pytest.mark.parametrize(
    "extras", [{}, {"mqtt_password": "", "db_password": "synthetic", "weather_api_key": "fixture"}]
)
def test_secrets_original_defaults_and_explicit_empty(extras: dict[str, str]) -> None:
    values = ConfigurationSecrets(
        unifi_password_effective=SecretStr('owned"literal'), **{k: SecretStr(v) for k, v in extras.items()}
    )
    result = render_secrets(values)
    assert result.get_secret_value() == ORIGINAL.get_template("secrets.yaml.j2").render(
        homeassistant_unifi_password_effective='owned"literal', **extras
    )
    assert "owned" not in repr(values)
    assert "literal" not in str(result)


@pytest.mark.parametrize(
    "name",
    ["automations.yaml", "scripts.yaml", "scenes.yaml", "groups.yaml", "persons.yaml", "presence_automations.yaml"],
)
def test_all_original_includes_exact(name: str) -> None:
    assert render_include(name).get_secret_value() == ORIGINAL.get_template(name + ".j2").render()


def test_unknown_template_and_input_are_not_silently_ignored() -> None:
    with pytest.raises(jinja2.TemplateNotFound):
        render_include("missing.yaml")
    with pytest.raises(ValidationError) as error:
        ConfigurationValues.model_validate({"unrecognized": "synthetic-private"})
    assert "synthetic-private" not in str(error.value)


@pytest.mark.parametrize(("latitude", "longitude"), [(51, 7), (0, -1), (51.2, -1.4), (51, 7.0)])
def test_coordinate_original_input_types_are_preserved(latitude: int | float, longitude: int | float) -> None:
    values = ConfigurationValues(latitude=latitude, longitude=longitude)
    assert type(values.latitude) is type(latitude)
    assert type(values.longitude) is type(longitude)
    rendered = render_configuration(HomeAssistantRuntimeConfig(), values).get_secret_value()
    assert rendered.count(f"latitude: {latitude}\n") == 2
    assert rendered.count(f"longitude: {longitude}\n") == 2


@pytest.mark.parametrize("value", [True, "51"])
def test_coordinate_bad_types_do_not_silently_coerce(value: object) -> None:
    with pytest.raises(ValidationError):
        ConfigurationValues.model_validate({"latitude": value})
